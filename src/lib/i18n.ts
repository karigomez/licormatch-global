export function formatPrice(usdAmount: number, country: CountryCode): string {
  const c = COUNTRIES[country];
  const value = usdAmount * c.rate;
  const rounded = c.currency === "COP" ? Math.round(value / 100) * 100 : Math.round(value * 100) / 100;
  const formatted = new Intl.NumberFormat(c.lang, {
    minimumFractionDigits: c.currency === "COP" ? 0 : 2,
    maximumFractionDigits: c.currency === "COP" ? 0 : 2,
  }).format(rounded);
  return `${c.symbol}${formatted}`;
}
